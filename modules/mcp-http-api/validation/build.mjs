import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

await build({
  entryPoints: [fileURLToPath(new URL('./schema-validator.mjs', import.meta.url))],
  outfile: fileURLToPath(new URL('../lambda/mcp-server/schema-validator.mjs', import.meta.url)),
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node22',
  minify: true,
  legalComments: 'none',
  banner: { js: '// Generated by validation/build.mjs. Edit validation/schema-validator.mjs and run npm ci && npm run build there.' },
});

const dependencies = [
  ['ajv', 'LICENSE'],
  ['ajv-formats', 'LICENSE'],
  ['fast-deep-equal', 'LICENSE'],
  ['fast-uri', 'LICENSE'],
  ['json-schema-traverse', 'LICENSE'],
  ['require-from-string', 'license'],
];
const notices = await Promise.all(dependencies.map(async ([name, filename]) => {
  const license = await readFile(new URL(`./node_modules/${name}/${filename}`, import.meta.url), 'utf8');
  const { version } = JSON.parse(await readFile(new URL(`./node_modules/${name}/package.json`, import.meta.url), 'utf8'));
  return `${name} ${version}\n${license.trim()}\n`;
}));
await writeFile(new URL('../lambda/mcp-server/schema-validator.LICENSE.txt', import.meta.url), notices.join('\n'));
